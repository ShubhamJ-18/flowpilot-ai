    async def summarize(self, text: str, max_length: str = "concise", tone: str = "professional") -> SummarizeResponse:
        sentences = [s.strip() for s in re.split(r'[.!?]+', text) if s.strip()]
        first_few = sentences[:2] if sentences else ["No significant content provided."]
        summary = " ".join(first_few) + "."
        key_points = [f"Highlight: {s[:60]}..." for s in sentences[:3]] if len(sentences) > 1 else ["Key message captured."]

        return SummarizeResponse(
            summary=summary,
            keyPoints=key_points,
            wordCount=len(summary.split()),
            tokensUsed=len(text.split()) + len(summary.split()),
            model=self.model_name
        )

    async def classify(self, text: str, categories: List[str], instruction: str = "") -> ClassifyResponse:
        text_lower = text.lower()
        selected_category = categories[0]
        confidence = 0.85
        reasoning = f"Matched primary criteria from text against '{selected_category}'."

        for cat in categories:
            cat_clean = cat.lower().replace("_", " ")
            if cat_clean in text_lower or any(word in text_lower for word in cat_clean.split()):
                selected_category = cat
                confidence = 0.94
                reasoning = f"Explicit keyword correlation identified with '{cat}'."
                break

        return ClassifyResponse(
            category=selected_category,
            confidence=confidence,
            reasoning=reasoning,
            tokensUsed=len(text.split()) + 25,
            model=self.model_name
        )

    async def extract(self, text: str, schema_fields: List[ExtractFieldSpec]) -> ExtractResponse:
        extracted = {}
        text_lower = text.lower()

        for field in schema_fields:
            fname = field.name.lower()
            if field.type == "number":
                # Look for numbers or currency
                num_match = re.search(r'\$?(\d+(\.\d+)?)', text)
                extracted[field.name] = float(num_match.group(1)) if num_match else 0.0
            elif field.type == "boolean":
                extracted[field.name] = "urgent" in text_lower or "asap" in text_lower or "critical" in text_lower
            elif field.type == "list":
                extracted[field.name] = [w for w in text.split()[:4]]
            else:
                # String extract: look for field name hint or default substring
                if "name" in fname or "customer" in fname or "vendor" in fname:
                    extracted[field.name] = "Acme Corp Customer"
                elif "topic" in fname or "issue" in fname:
                    extracted[field.name] = "Account Access & Billing Discrepancy"
                elif "sentiment" in fname:
                    extracted[field.name] = "Negative (Urgent Concern)" if "urgent" in text_lower else "Neutral"
                else:
                    extracted[field.name] = f"Extracted {field.name} data"

        return ExtractResponse(
            extracted=extracted,
            tokensUsed=len(text.split()) + len(extracted) * 15,
            model=self.model_name
        )
